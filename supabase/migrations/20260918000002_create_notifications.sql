revoke all on function public.notify_diamond_status() from public, anon, authenticated;
revoke all on function public.notify_announcement() from public, anon, authenticated;

-- Enable database-change delivery for the live unread badge when Realtime exists.
do $$
begin
  if exists (
    select 1 from pg_publication where pubname = 'supabase_realtime'
  ) and not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'notifications'
  ) then
    execute 'alter publication supabase_realtime add table public.notifications';
  end if;
end;
$$;

